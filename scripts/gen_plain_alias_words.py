"""Generate earwitness/data/plain-alias-words.json (ASK-WAYFAIR H1, lead AW-4/AW-6).

It reads the ad_brand_aliases keys of rows with no display name whose every
word is a plain English word (a lower-case entry of a word list) and sorts
them by their attributed detected ads (ad_reads with a brand_assocs basis of
confirmed or suggested):

- "words": one word with fewer than --min-ads attributed ads. Ask looks
  for these only when capitalised in an item with ad wording or citing
  their ad, so "her", "store" or "next" read as a brand only there.
- "capital_only_words": one word with --min-ads or more attributed ads
  ("progressive", "chase"), or a phrase with fewer ("get up", "magic spoon").
  Ask looks for these only when capitalised (every word outside the small
  words), so "get up to 80% off" is not a brand and "Magic Spoon" is; a
  phrase also in lower case where the plain words are looked for. A
  phrase is listed as its lower-case key.

Ask matches every other row with no display name in any case, including
phrases with --min-ads or more ads ("simply safe"; multi-word names count in
any case, S9).

Ask computes these lists for each workspace at load by the same rules
(ask_contract.plain_alias_words, ASK-CHECK-WORDS); this file is the
fallback, and its words the dictionary where no word file is installed.

  python3 scripts/gen_plain_alias_words.py --db <workspace.sqlite3> \
      [--words /usr/share/dict/words] [--min-ads 3] [--out earwitness/data/plain-alias-words.json]

The DB is opened read-only. The output is sorted and deterministic.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from earwitness.app import ask_contract as _contract  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "earwitness" / "data" / "plain-alias-words.json"


# The rules live in ask_contract, so Ask computes the same lists per workspace
# at load (ASK-CHECK-WORDS); this file is the fallback.
build = _contract.plain_alias_words


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", required=True)
    ap.add_argument("--words", default="/usr/share/dict/words")
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--min-ads", type=int, default=3)
    a = ap.parse_args()
    words = {w.strip() for w in Path(a.words).read_text(encoding="utf-8").splitlines()
             if w.strip() and w.strip().islower()}
    con = sqlite3.connect(f"file:{a.db}?mode=ro", uri=True)
    try:
        result = build(con, words, a.min_ads)
    finally:
        con.close()
    doc = {"header": "Generated by scripts/gen_plain_alias_words.py (ASK-WAYFAIR H1, lead AW-4/AW-6): "
                     "no-display alias keys made only of plain words. words: one word with fewer than "
                     "min_ads attributed ads (skipped). capital_only_words: one word with min_ads or more, "
                     "or a phrase with fewer (capitalised only).",
           "source_words_sha256": hashlib.sha256(Path(a.words).read_bytes()).hexdigest(),
           "min_ads": a.min_ads, "count": len(result["plain"]),
           "capital_only_count": len(result["capital_only"]),
           "words": result["plain"], "capital_only_words": result["capital_only"]}
    Path(a.out).write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"plain {len(result['plain'])}, capital-only (advertising) {len(result['capital_only'])}")


if __name__ == "__main__":
    main()
